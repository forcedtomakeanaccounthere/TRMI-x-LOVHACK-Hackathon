import asyncio
import json
import logging
import time

from app.config import get_settings
from app.guardrails import (
    UNTRUSTED_RULE,
    clean_text,
    flag_injection,
    urls_in,
    wrap_untrusted,
)
from app.schemas import (
    MAX_HUDDLE_BLOCKS,
    MAX_HUDDLE_SEGMENTS,
    HuddleBlockIn,
    HuddleNotePoint,
    HuddleNotesData,
    HuddleNotesRequest,
    HuddleSegmentIn,
)
from app.services.providers import (
    available,
    complete_json,
    configured_providers,
    record_failure,
    record_success,
)

log = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You summarize a voice huddle (meeting call) from its transcript and optional referenced "
    "document blocks. Produce meeting notes with summary, key_points, decisions, action_items, "
    "and open_questions. Every point in key_points, decisions, action_items, and open_questions "
    "MUST cite the segment_ids from the transcript that support it in segment_ids (a list of "
    "existing segment id strings). Do not invent segment ids. For action_items, set owner to "
    "the person assigned if mentioned, or null if none. "
    "Write plain text: no HTML, no markdown links.\n\n" + UNTRUSTED_RULE
)

# Output limits: what fits a notes panel, whatever the model returns.
MAX_ITEMS = 8
MAX_SUMMARY_CHARS = 500
MAX_ITEM_CHARS = 500
MAX_OWNER_CHARS = 40

# Not worth starting a provider call with less time than this left.
MIN_ATTEMPT_SECONDS = 5.0


class HuddleNotesError(Exception):
    pass


class NoProviderError(HuddleNotesError):
    pass


async def generate_huddle_notes(req: HuddleNotesRequest) -> HuddleNotesData:
    providers = configured_providers()
    if not providers:
        raise NoProviderError("No AI provider configured: set at least one *_API_KEY")

    settings = get_settings()
    segments = req.segments[:MAX_HUDDLE_SEGMENTS]
    blocks = req.blocks[:MAX_HUDDLE_BLOCKS]
    if len(req.segments) > MAX_HUDDLE_SEGMENTS or len(req.blocks) > MAX_HUDDLE_BLOCKS:
        log.info(
            "Huddle notes uses the first %d of %d segments and %d of %d blocks",
            len(segments),
            len(req.segments),
            len(blocks),
            len(req.blocks),
        )
    user = build_prompt(req.title, segments, blocks)

    # Fall through to the next provider on any failure: API error, timeout or bad output.
    # One deadline covers the whole chain; each attempt gets what is left, up to the per-call cap.
    deadline = time.monotonic() + settings.huddle_notes_deadline_seconds
    failures = []
    for provider in available(providers):
        remaining = deadline - time.monotonic()
        if remaining < MIN_ATTEMPT_SECONDS:
            failures.append("deadline reached")
            break
        started = time.monotonic()
        attempt_seconds = min(settings.ai_timeout_seconds, remaining)
        try:
            notes = await asyncio.wait_for(
                complete_json(
                    provider, SYSTEM_PROMPT, user, HuddleNotesData, timeout=attempt_seconds
                ),
                timeout=attempt_seconds,
            )
        except Exception as e:
            record_failure(provider)
            log.warning(
                "Huddle notes via %s (%s) failed after %.1f s: %r",
                provider.name,
                provider.model,
                time.monotonic() - started,
                e,
            )
            failures.append(f"{provider.name}: {type(e).__name__}")
            continue
        record_success(provider)
        log.info(
            "Huddle notes generated by %s (%s) in %.1f s after %d fallback(s)",
            provider.name,
            provider.model,
            time.monotonic() - started,
            len(failures),
        )
        return sanitize_huddle_notes(notes, segments, blocks)

    raise HuddleNotesError(f"All AI providers failed ({', '.join(failures)})")


def build_prompt(
    title: str, segments: list[HuddleSegmentIn], blocks: list[HuddleBlockIn]
) -> str:
    """The user message: untrusted transcript and blocks wrapped in tags."""
    flag_injection("transcript", "\n".join(s.text for s in segments))
    if blocks:
        flag_injection("blocks", "\n".join(b.excerpt for b in blocks))
    parts = [
        wrap_untrusted("title", title),
        wrap_untrusted("transcript", json.dumps([s.model_dump() for s in segments])),
    ]
    if blocks:
        parts.append(wrap_untrusted("blocks", json.dumps([b.model_dump() for b in blocks])))
    return "\n\n".join(parts)


def sanitize_huddle_notes(
    notes: HuddleNotesData,
    segments: list[HuddleSegmentIn],
    blocks: list[HuddleBlockIn],
) -> HuddleNotesData:
    """Makes the model's notes safe to show: plain text, capped lengths/items, and valid segment
    ids."""
    allowed_urls = urls_in(*(s.text for s in segments), *(b.excerpt for b in blocks))
    valid_segment_ids = {s.id for s in segments}

    def clean(text: str, max_chars: int = MAX_ITEM_CHARS) -> str:
        return clean_text(text, allowed_urls, max_chars)

    def clean_points(points: list[HuddleNotePoint]) -> list[HuddleNotePoint]:
        cleaned: list[HuddleNotePoint] = []
        for p in points:
            text = clean(p.text, MAX_ITEM_CHARS)
            if not text:
                continue
            valid_sids = [sid for sid in p.segment_ids if sid in valid_segment_ids]
            owner = clean_text(p.owner, set(), MAX_OWNER_CHARS) if p.owner else None
            cleaned.append(HuddleNotePoint(text=text, owner=owner, segment_ids=valid_sids))
        return cleaned[:MAX_ITEMS]

    return HuddleNotesData(
        summary=clean(notes.summary, MAX_SUMMARY_CHARS),
        key_points=clean_points(notes.key_points),
        decisions=clean_points(notes.decisions),
        action_items=clean_points(notes.action_items),
        open_questions=clean_points(notes.open_questions),
    )
