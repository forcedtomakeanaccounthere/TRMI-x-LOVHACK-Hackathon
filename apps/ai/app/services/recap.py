import asyncio
import json
import logging
import time

from app.config import get_settings
from app.schemas import RecapData, RecapRequest
from app.services.providers import (
    available,
    complete_json,
    configured_providers,
    record_failure,
    record_success,
)

log = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You summarize a group's shared reading session. Focus on what the people "
    "highlighted and discussed, not just the document."
)


# Not worth starting a provider call with less time than this left.
MIN_ATTEMPT_SECONDS = 5.0


class RecapError(Exception):
    pass


class NoProviderError(RecapError):
    pass


async def generate_recap(req: RecapRequest) -> RecapData:
    providers = configured_providers()
    if not providers:
        raise NoProviderError("No AI provider configured: set at least one *_API_KEY")

    settings = get_settings()
    document = req.text[: settings.max_document_chars]
    highlights = json.dumps([h.model_dump() for h in req.highlights])
    comments = json.dumps([c.model_dump() for c in req.comments])
    user = (
        f"Document: {req.title}\n\n{document}\n\n"
        f"Highlights:\n{highlights}\n\nComments:\n{comments}"
    )

    # Fall through to the next provider on any failure: API error, timeout or bad output.
    # One deadline covers the whole chain; each attempt gets what is left, up to the per-call cap.
    deadline = time.monotonic() + settings.recap_deadline_seconds
    failures = []
    for provider in available(providers):
        remaining = deadline - time.monotonic()
        if remaining < MIN_ATTEMPT_SECONDS:
            failures.append("deadline reached")
            break
        started = time.monotonic()
        attempt_seconds = min(settings.ai_timeout_seconds, remaining)
        try:
            # The SDK timeout is per HTTP request, and the client retries once, so on its own a
            # call could run for twice as long. wait_for cancels the whole attempt, retries and
            # all, when its share of the deadline runs out.
            recap = await asyncio.wait_for(
                complete_json(
                    provider, SYSTEM_PROMPT, user, RecapData, timeout=attempt_seconds
                ),
                timeout=attempt_seconds,
            )
        except Exception as e:
            record_failure(provider)
            log.warning(
                "Recap via %s (%s) failed after %.1f s: %r",
                provider.name,
                provider.model,
                time.monotonic() - started,
                e,
            )
            failures.append(f"{provider.name}: {type(e).__name__}")
            continue
        record_success(provider)
        log.info(
            "Recap generated by %s (%s) in %.1f s after %d fallback(s)",
            provider.name,
            provider.model,
            time.monotonic() - started,
            len(failures),
        )
        return recap

    raise RecapError(f"All AI providers failed ({', '.join(failures)})")
